import AppKit
import ApplicationServices
import IslandCore

/// Watches the system clipboard and records copies into `ClipboardHistory`.
///
/// macOS has no "clipboard changed" notification, so like every clipboard manager
/// this checks `changeCount` twice a second, which costs almost nothing.
@MainActor
final class ClipboardMonitor: ObservableObject {
    let history: ClipboardHistory
    @Published var isPaused: Bool {
        didSet { UserDefaults.standard.set(isPaused, forKey: "clipboard.paused") }
    }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Password managers mark secrets with these types (see nspasteboard.org); never store them.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(history: ClipboardHistory) {
        self.history = history
        isPaused = UserDefaults.standard.bool(forKey: "clipboard.paused")
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isPaused else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            history.addFiles(urls.map(\.path), sourceApp: source)
        } else if let text = pasteboard.string(forType: .string) {
            history.addText(text, sourceApp: source)
        } else if let image = readImage() {
            history.addImage(png: image.png, width: image.width, height: image.height, sourceApp: source)
        }
    }

    private func readImage() -> (png: Data, width: Double, height: Double)? {
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return (png, Double(rep.pixelsWide), Double(rep.pixelsHigh))
    }

    // MARK: Copy back / paste

    /// Puts an item back on the clipboard (without re-recording it as a new copy).
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text, forType: .string)
        case .files:
            pasteboard.writeObjects(item.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let url = history.imageURL(for: item), let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        }
        lastChangeCount = pasteboard.changeCount
        history.markUsed(item.id)
    }

    /// Whether Island may send ⌘V to other apps (Accessibility permission).
    var canAutoPaste: Bool { AXIsProcessTrusted() }

    /// Shows the system prompt that leads to Settings → Privacy → Accessibility.
    func requestAutoPastePermission() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// Sends ⌘V to whichever app is frontmost.
    func sendPasteKeystroke() {
        guard canAutoPaste else { return }
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
